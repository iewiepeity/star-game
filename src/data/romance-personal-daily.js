export function romanceDailyPool(id, stage) {
  if (!STAGES.includes(stage)) return [];
  return [...(ROMANCE_PERSONAL_DAILY[id]?.[stage] || []), ...intimacy(id, stage), ...ROMANCE_DAILY_STORIES[stage]];
}

export function romanceDailyBond(scene, choice) {
  if (!scene || !choice) return null;
  if (choice.bond) return choice.bond;
  if ((choice.effect?.trust || 0) < 0 || (choice.effect?.affection || 0) < 0 || (choice.effect?.hostility || 0) > 0) return null;
  if (["end-of-day", "dinner-incomplete", "old-argument"].includes(scene.id)) return "care";
  if (["career-direction", "two-careers"].includes(scene.id)) return "work";
  if (["shared-shopping", "home-is-not-a-set", "ordinary-celebration"].includes(scene.id)) return "reliability";
  if (["same-table", "familiar-drink", "familiar-silence", "same-place-new-day", "new-question"].includes(scene.id)) return "private";
  return null;
}
