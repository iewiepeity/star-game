export function endingStorySummary(endingId, { snapshot, portfolio, bestRel, trigger }) {
  const ending = ENDING_COPY[endingId] || ENDING_COPY.unfinished;
  const opening = trigger === "death" ? "" : trigger === "retire"
    ? `第 ${snapshot.week} 週，你決定提早結束這段旅程。童年卡片背面的五年之約，這次由你自己改了交卷時間。`
    : "五年之約到了。你把桌邊那張童年卡片放平，重新看見杯子曾經壓住的半顆星星。";
  const pieces = [opening, ending[1]];
  const work = portfolio.bestWork;
  if (work) pieces.push(`作品紀錄裡，品質最高的是《${work.title}》。你留下了 ${portfolio.works} 部完成作品${portfolio.originals ? `，其中 ${portfolio.originals} 部由原創開始` : ""}；每一部都比最初空白的履歷，多了一份真正做過的事。`);
  else pieces.push(trigger === "death" ? "作品欄仍然空白。沒有完成的作品，無法代替這個人曾經存在過的全部。" : "作品欄目前沒有完成紀錄。你把這一欄如實留下，不用一次尚未完成的嘗試，冒充已經拍完的成品。下一步可以重新決定。 ");
  const doctrine = snapshot.careerDoctrine || {};
  if (trigger !== "death") {
    const earlier = doctrine.year4 || doctrine.year3;
    if (DOCTRINE_CLOSURES[earlier?.id]) pieces.push(DOCTRINE_CLOSURES[earlier.id]);
    if (DOCTRINE_CLOSURES[doctrine.year5?.id]) pieces.push(DOCTRINE_CLOSURES[doctrine.year5.id]);
  }
  const name = bestRel && NPCS[bestRel.npcId]?.name;
  if (name && ["committed", "engaged", "married"].includes(bestRel.romance)) {
    const status = { committed: "交往", engaged: "訂婚", married: "婚姻" }[bestRel.romance];
    pieces.push(trigger === "death"
      ? `你與${name}之間已走到${status}。留下來的人仍有往後的生活；這段關係的重量，不需要用永遠停止前進來證明。`
      : `${name}與你的關係走到${status}。${(bestRel.trust || 0) >= 75 ? "那些願意聽完、願意解釋的時刻，累積成了現在的信任。" : "名分已經確定，信任仍有需要慢慢照顧的地方；一個結局不能替你們省略往後的溝通。"}`);
  } else if (name && bestRel.closeness >= 30) {
    pieces.push(`${name}留在這段人生的重要往來裡。${trigger === "death" ? "共同走過的部分到此留下，不必替沒說出口的話硬加一個答案。" : "這段關係目前沒有被確認為伴侶；它仍然有實際相處過的分量，不需要借一場不存在的告白來收尾。"}`);
  } else if (trigger !== "death") pieces.push("這次沒有一段親密關係替故事收尾。你把自己的名字寫在卡片背面；一個人的生活，也值得被認真安排。 ");
  if (trigger !== "death" && snapshot.currentAgencyId === null) pieces.push("此刻你仍是自由身，沒有經紀合約替下一幕預留答案。這份自主與必須自己張羅的工作，會一起跟著你往前。 ");
  if (trigger !== "death" && (snapshot.fatigue >= 75 || snapshot.health <= 50)) pieces.push("收尾時，你仍帶著明顯的疲憊。成績單不能讓身體立刻恢復；這次整理到這裡，先把休息留給自己。 ");
  else if (trigger !== "death") pieces.push("窗外的看板又換了一輪。你沒有把卡片收進垃圾桶，也不再讓它單獨替自己決定下一幕。 ");
  return pieces.filter(Boolean).join("\n\n");
}
