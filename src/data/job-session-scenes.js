export const JOB_SESSION_SCENES = Object.fromEntries(Object.entries(copy).map(([category, rows]) => [category,
  rows.map(([title, text], index) => ({ id: `job-session-${category}-${index + 1}`, label: "持續製作", title, text })),
]));
export function continuingJobScene(job, record, recent = []) {
  const category = job.category === "歌曲" ? "music" : job.category === "綜藝" ? "variety" : job.category === "廣告" ? "advertising" : "drama";
  const pool = JOB_SESSION_SCENES[category];
  const own = new Set((record.continuationHistory || []).map((item) => item.sceneId));
  const fresh = pool.filter((scene) => !own.has(scene.id));
  const candidates = fresh.length ? fresh : pool;
  const lastSeen = (scene) => recent.findLastIndex((item) => item.sceneId === scene.id);
  return [...candidates].sort((a, b) => lastSeen(a) - lastSeen(b))[0];
}
