export function jobProductionScene(job,record,{completed=false}={}){
 const pool=SCENES[job?.category]||SCENES.廣告,total=Math.max(1,job?.sessions||1),done=Math.max(1,record?.completedSessions||1);
 const index=completed?3:Math.min(2,Math.floor((done-1)/total*4));
 const[title,text]=pool[index];
 const pressure=job?.stars>=4?" 這是一份高規格製作，任何細節都可能被放大檢視。":"";
 return{stage:index,title,text:text+pressure,label:["開工","磨合","關鍵場次","殺青"][index]};
}

