const playedChoice = (game, id) => [...(game.eventHistory || [])].reverse().find(item => item.id === id);

export function careerChapterText(phase, game) {
  const works = game.completedWorks || [];
  const last = works.at(-1);
  const prior = playedChoice(game, `career-phase-${phase.year - 1}`);
  const opening = {
    1: "桌上的童年卡片被風吹倒了。你找來一個杯子壓住它，杯底恰好遮住半顆星星。接下來的一年，繳費通知、練習和試鏡，都得和這個願望放在同一張桌上。",
    2: last ? `你打開《${last.title}》的工作紀錄，旁邊擺著最初那張空白履歷。那些完成過的部分已經有名字；接下來的半年，你想把力氣往哪裡放？` : "你重新打開履歷，作品欄還沒有完成紀錄。這件事不漂亮，也不需要換個說法。先選定半年要練的方向，再把能負擔的生活安排好，仍然是一個可以開始的計畫。",
    3: "徵選名單更新了。你在螢幕前停了一會兒，又把頁面往下捲；每個名額背後，都有同樣在等待的人。第三年，你得決定如何看待和自己站在同一條線上的人。",
    4: "你把行程表印出來，在每一格旁邊寫下它占用的東西：準備時間、體力、回家吃飯的晚上。空白很快不夠用了。第四年的問題不再只是要不要努力，而是哪些代價值得繼續付。",
    5: "整理抽屜時，童年卡片從一疊單據裡露出一角。你把它抽出來，背面的日期已經走到最後一年。那個只會畫巨大星星的小孩，當時沒有替你規定結局。",
  }[phase.year];
  const echo = prior ? `去年你選過「${prior.choiceLabel}」。新的一頁不會抹掉那個決定，只是讓你看看，它把你帶到了哪裡。` : "";
  const position = phase.year > 1 ? (game.currentAgencyId
    ? "現在有公司一起處理工作，但答應什麼、拒絕什麼，仍要由你看清楚。"
    : "你目前以自由身接洽工作。報價、排程和每一封回信，都得自己留意；沒有人能替你把決定轉交出去。") : "";
  return [opening, echo, position, phase.pressure].filter(Boolean).join("\n\n");
}

