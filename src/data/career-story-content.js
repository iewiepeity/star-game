export function doctrineScene(game, doctrine) {
  const pool = DOCTRINE_SCENES[doctrine.id];
  if (!pool) return null;
  const previous = (game.doctrineEventHistory || []).filter(item => item.id === doctrine.id && item.week < game.week).length;
  const copy = pool[previous % pool.length];
  return copy;
}
