export function registerCityRooms(rooms, spots) {
  for (const [id, def] of Object.entries(entries)) {
    const [col, row, cols, rows] = def.cell;
    const crop =
      rows === 1
        ? [col * 512, 120, 512, 680]
        : [(col * 1536) / cols, row ? 505 : 0, 1536 / cols, row ? 445 : 460];
    const scale = Math.min(890 / crop[2], 596 / crop[3]);
    const width = crop[2] * scale,
      height = crop[3] * scale;
    const rect = { x: (960 - width) / 2, y: (640 - height) / 2, width, height };
    const artCrop = ART_BOUNDS[id] || crop;
    const artRect = {
      x: rect.x + (artCrop[0] - crop[0]) * scale,
      y: rect.y + (artCrop[1] - crop[1]) * scale,
      width: artCrop[2] * scale,
      height: artCrop[3] * scale,
    };
    const pt = ([x, y]) => ({
      x: rect.x + (x * width) / 100,
      y: rect.y + (y * height) / 100,
    });
    const polygon = (points) => points.map(pt);
    const hit = (x, y, w = 12, h = 14) =>
      polygon([
        [x - w / 2, y - h / 2],
        [x + w / 2, y - h / 2],
        [x + w / 2, y + h / 2],
        [x - w / 2, y + h / 2],
      ]);
    const make = (itemId, name, a, action) => ({
      id: itemId,
      name,
      action,
      icon: "",
      ...pt(a),
      target: pt(a.slice(2)),
      hit: hit(...a),
    });
    const metadata = CITY_CATALOG[id];
    const serviceName =
      {
        film_company: "片場場務與徵選窗口",
        studio: "場務工作台",
        record_company: "Demo 收件與製作行政",
        recording: "錄音與課程控制台",
        livehouse: "售票與演出資訊",
        radio: "主持課程服務台",
        business: "大樓接待桌",
        media_company: "製作與拍攝助理窗口",
        library: "館藏與寫作課程",
        cinema: "電影售票處",
        gallery: "展覽資訊台",
        market: "市集服務攤",
        temple: "求籤服務桌",
        dance: "鏡前舞蹈練習",
        gym: "健身服務台",
        beauty: "造型諮詢台",
        clinic: "醫療諮詢台",
        restaurant: "餐酒館接待吧台",
        park: "河岸導覽牌",
        beach: "沙灘導覽牌",
        airport: "航廈服務台",
        editing_room: "剪輯工作台",
      }[id] || "公司接待桌";
    rooms[id] = {
      name: metadata.name,
      subtitle: metadata.district,
      color: "#b29b78",
      asset: `assets/pixel/city/${def.atlas}.webp`,
      crop: artCrop,
      rect: artRect,
      floor: polygon(def.floor),
      blocks: def.blocks.map(polygon),
      foreground: [],
      entry: pt(def.entry),
      objects: [
        make("service", serviceName, def.service, "services"),
        make(
          "detail",
          def.detailName,
          def.detail,
          def.detailAction || "detail",
        ),
        {
          id: "door",
          name: id.startsWith("agency_") ? "回到商務中心" : "回到城市地圖",
          action: id.startsWith("agency_") ? "business-exit" : "travel",
          icon: "",
          ...pt(def.entry),
          target: pt(def.entry),
          hit: hit(...def.entry, 18, 16),
        },
      ],
      route: [pt(def.entry), pt(def.service.slice(2)), pt(def.detail.slice(2))],
    };
    // Collision polygons are floor footprints, never visual silhouettes.
    // Public walkways must not repaint background over a character's head.
    // Only independently reviewed furniture silhouettes become foreground.
    rooms[id].foreground = (SCENE_OCCLUDERS[id] || []).map(
      ([depth, points]) => ({
        depth: (rect.y + (depth - crop[1]) * scale) / 0.625,
        polygon: points.map(([x, y]) => ({
          x: rect.x + (x - crop[0]) * scale,
          y: rect.y + (y - crop[1]) * scale,
        })),
      }),
    );
    if (id === "market")
      rooms[id].artOutline = MARKET_OUTLINE.map(([x, y]) => ({
        x: rect.x + (x - crop[0]) * scale,
        y: rect.y + (y - crop[1]) * scale,
      }));
    spots[id] = {
      service: { kinds: ["read", ...(id === "dance" ? ["dance"] : [])] },
      detail: { kinds: ["read"] },
    };
  }
  for (const [id, room] of Object.entries(rooms)) {
    room.asset ||= `assets/pixel/${id}.png`;
    room.rect ||= { x: 0, y: 0, width: 960, height: 640 };
    room.venue =
      id === "tv" ? "tv_company" : id.startsWith("agency_") ? "business" : id;
  }
}
export function roomIllustration(room, alt = "") {
  if (!room.crop) return `<img src="${room.asset}" alt="${alt || room.name}">`;
  const clipId = `room-art-${room.crop.join("-")}`;
  return `<svg class="room-illustration" role="img" aria-label="${alt || room.name}" viewBox="${room.crop.join(" ")}"><defs><clipPath id="${clipId}">${room.artOutline ? `<polygon points="${MARKET_OUTLINE.map((p) => p.join(",")).join(" ")}"/>` : `<rect x="${room.crop[0]}" y="${room.crop[1]}" width="${room.crop[2]}" height="${room.crop[3]}"/>`}</clipPath></defs><image href="${room.asset}" width="1536" height="1024" clip-path="url(#${clipId})"/></svg>`;
}
